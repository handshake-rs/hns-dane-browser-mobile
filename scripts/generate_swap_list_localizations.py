#!/usr/bin/env python3
"""Generate the Android swap-list resources from reviewed locale text."""

from __future__ import annotations

import argparse
from html import escape
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "android/app/src/main/res"
SOURCE = ROOT / "localization/wallet-swap-list.json"
TOKEN = re.compile(r"%(?:\d+\$)?[a-zA-Z%]")


def android_text(value: str) -> str:
    return escape(
        value.replace("\\", "\\\\")
        .replace("'", "\\'")
        .replace('"', '\\"')
        .replace("\n", r"\n"),
        quote=False,
    )


def render(keys: list[str], values: dict[str, str]) -> str:
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<!-- Generated by scripts/generate_swap_list_localizations.py. -->',
        "<resources>",
    ]
    lines.extend(
        f'    <string name="{key}">{android_text(values[key])}</string>'
        for key in keys
    )
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    keys = data["keys"]
    translations = data["translations"]
    if data["schema"] != 1 or len(keys) != len(set(keys)):
        raise ValueError("invalid swap-list localization schema or duplicate keys")
    base = {
        element.get("name"): "".join(element.itertext()).replace(r"\n", "\n")
        for element in ET.parse(RES / "values/strings.xml").getroot()
        if element.tag == "string"
    }
    locales = {
        path.name.removeprefix("values-")
        for path in RES.glob("values-*")
        if path.is_dir()
    }
    if set(translations) != locales:
        raise ValueError("swap-list translation locales differ from Android locales")
    for locale, values in translations.items():
        if set(values) != set(keys):
            raise ValueError(f"{locale}: swap-list translation keys differ")
        for key in keys:
            if not isinstance(values[key], str) or not values[key]:
                raise ValueError(f"{locale}/{key}: translation is empty")
            if sorted(TOKEN.findall(values[key])) != sorted(TOKEN.findall(base[key])):
                raise ValueError(f"{locale}/{key}: format tokens differ")
            if values[key].count("\n") != base[key].count("\n"):
                raise ValueError(f"{locale}/{key}: line breaks differ")
        path = RES / f"values-{locale}/wallet_swap_list.xml"
        expected = render(keys, values)
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                raise ValueError(f"{path}: generated swap-list translations differ")
        else:
            path.write_text(expected, encoding="utf-8")
    print(f"Swap-list translations verified for {len(locales)} locales" if args.check
          else f"Generated swap-list translations for {len(locales)} locales")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
